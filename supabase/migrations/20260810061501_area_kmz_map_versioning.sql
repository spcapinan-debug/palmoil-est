create or replace function public.publish_area_map_version(
  p_version_id uuid,
  p_deployment_context text,
  p_actor_profile_id uuid
)
returns public.area_map_versions
language plpgsql
security invoker
set search_path = ''
as $$
declare
  target public.area_map_versions;
begin
  if nullif(trim(p_deployment_context), '') is null then
    raise exception using errcode = '22023', message = 'deployment context is required';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('area-map:' || p_deployment_context, 0));

  select * into target
  from public.area_map_versions
  where id = p_version_id and deployment_context = p_deployment_context
  for update;

  if target.id is null then
    raise exception using errcode = 'P0002', message = 'Area map version not found';
  end if;
  if target.status = 'published' then
    return target;
  end if;
  if target.status <> 'validated' then
    raise exception using errcode = '22023', message = 'Only a validated Area map version can be published';
  end if;
  if target.feature_count <= 0
     or target.processed_storage_path is null
     or jsonb_typeof(target.bounds) <> 'array'
     or jsonb_array_length(target.bounds) <> 4
     or jsonb_typeof(target.validation_errors) <> 'array'
     or jsonb_array_length(target.validation_errors) > 0
     or target.duplicate_count > 0
     or target.conflict_count > 0
     or (target.unmatched_count > 0 and not target.unmatched_acknowledged) then
    raise exception using errcode = '22023', message = 'Area map version does not pass the publish gate';
  end if;

  update public.area_map_versions
  set status = 'archived', archived_at = now()
  where deployment_context = p_deployment_context and status = 'published' and id <> target.id;

  update public.area_map_versions
  set status = 'published',
      published_by_profile_id = p_actor_profile_id,
      published_at = now(),
      archived_at = null
  where id = target.id
  returning * into target;

  return target;
end;
$$;

create or replace function public.rollback_area_map_version(
  p_source_version_id uuid,
  p_deployment_context text,
  p_actor_profile_id uuid,
  p_reason text default null
)
returns public.area_map_versions
language plpgsql
security invoker
set search_path = ''
as $$
declare
  source public.area_map_versions;
  restored public.area_map_versions;
begin
  if nullif(trim(p_deployment_context), '') is null then
    raise exception using errcode = '22023', message = 'deployment context is required';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('area-map:' || p_deployment_context, 0));

  select * into source
  from public.area_map_versions
  where id = p_source_version_id and deployment_context = p_deployment_context
  for update;

  if source.id is null then
    raise exception using errcode = 'P0002', message = 'Rollback source version not found';
  end if;
  if source.processed_storage_path is null
     or source.feature_count <= 0
     or jsonb_typeof(source.validation_errors) <> 'array'
     or jsonb_array_length(source.validation_errors) > 0
     or source.duplicate_count > 0
     or source.conflict_count > 0 then
    raise exception using errcode = '22023', message = 'Rollback source is not a valid published artifact';
  end if;

  insert into public.area_map_versions (
    deployment_context, status, source_version_id, original_file_name,
    raw_storage_path, processed_storage_path, sha256, file_size_bytes,
    feature_count, matched_count, unmatched_count, master_without_map_count,
    duplicate_count, conflict_count, bounds, source_metadata,
    reconciliation_summary, validation_errors, unmatched_acknowledged,
    uploaded_by_profile_id
  ) values (
    p_deployment_context, 'validated', source.id, source.original_file_name,
    source.raw_storage_path, source.processed_storage_path, source.sha256, source.file_size_bytes,
    source.feature_count, source.matched_count, source.unmatched_count, source.master_without_map_count,
    source.duplicate_count, source.conflict_count, source.bounds,
    source.source_metadata || jsonb_build_object(
      'rollbackOfVersionId', source.id,
      'rollbackOfVersionNo', source.version_no,
      'rollbackReason', coalesce(p_reason, '')
    ),
    source.reconciliation_summary, source.validation_errors, true,
    p_actor_profile_id
  )
  returning * into restored;

  update public.area_map_versions
  set status = 'archived', archived_at = now()
  where deployment_context = p_deployment_context and status = 'published';

  update public.area_map_versions
  set status = 'published',
      published_by_profile_id = p_actor_profile_id,
      published_at = now(),
      archived_at = null
  where id = restored.id
  returning * into restored;

  return restored;
end;
$$;

revoke all on function public.publish_area_map_version(uuid, text, uuid) from public, anon, authenticated;
revoke all on function public.rollback_area_map_version(uuid, text, uuid, text) from public, anon, authenticated;
grant execute on function public.publish_area_map_version(uuid, text, uuid) to service_role;
grant execute on function public.rollback_area_map_version(uuid, text, uuid, text) to service_role;
