create table if not exists public.area_map_versions (
  id uuid primary key default gen_random_uuid(),
  version_no bigint generated by default as identity unique,
  deployment_context text not null default 'production',
  status text not null default 'draft'
    check (status in ('draft', 'validated', 'published', 'rejected', 'archived')),
  source_version_id uuid references public.area_map_versions(id) on delete restrict,
  original_file_name text not null,
  raw_storage_path text,
  processed_storage_path text,
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  file_size_bytes bigint not null check (file_size_bytes > 0 and file_size_bytes <= 3145728),
  feature_count integer not null default 0 check (feature_count >= 0),
  matched_count integer not null default 0 check (matched_count >= 0),
  unmatched_count integer not null default 0 check (unmatched_count >= 0),
  master_without_map_count integer not null default 0 check (master_without_map_count >= 0),
  duplicate_count integer not null default 0 check (duplicate_count >= 0),
  conflict_count integer not null default 0 check (conflict_count >= 0),
  bounds jsonb not null default '[]'::jsonb,
  source_metadata jsonb not null default '{}'::jsonb,
  reconciliation_summary jsonb not null default '{}'::jsonb,
  validation_errors jsonb not null default '[]'::jsonb,
  unmatched_acknowledged boolean not null default false,
  uploaded_by_profile_id uuid references public.profiles(id) on delete set null,
  published_by_profile_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  published_at timestamptz,
  archived_at timestamptz,
  constraint area_map_versions_storage_paths check (
    (status in ('draft', 'rejected'))
    or (raw_storage_path is not null and processed_storage_path is not null)
  )
);

comment on table public.area_map_versions is
  'Immutable KMZ/processed GeoJSON version metadata. Canonical business identity remains public.blocks.id.';
comment on column public.area_map_versions.deployment_context is
  'Server-derived context (production or isolated preview/UAT branch) so preview publication cannot change the production active map.';

create unique index if not exists ux_area_map_versions_one_published_context
  on public.area_map_versions (deployment_context)
  where status = 'published';
create index if not exists area_map_versions_context_version_idx
  on public.area_map_versions (deployment_context, version_no desc);
create index if not exists area_map_versions_source_version_idx
  on public.area_map_versions (source_version_id)
  where source_version_id is not null;

